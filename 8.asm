xor     r8, r8                       ; Обнуляем счётчик неотрицательных чисел

test    rcx, rcx                     ; Проверяем, пуст ли массив
jz      empty                        ; Если RCX = 0, пропускаем цикл

loop:
    dec     rcx                      ; Переходим к предыдущему индексу
    mov     eax, dword [rdi + rcx*4] ; Загружаем элемент массива

    test    eax, eax                 ; Проверяем знак элемента
    js      negative                 ; Если отрицательный — пропускаем увеличение
    inc     r8                       ; Увеличиваем счётчик

negative:
    test    rcx, rcx                 ; Проверяем, остались ли элементы
    jnz     loop                     ; Если да — продолжаем цикл

empty:
    mov     rax, r8                  ; Помещаем результат в RAX

