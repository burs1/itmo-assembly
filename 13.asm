; Напишите код, разворачивающий биты 16 битного числа в обратном порядке
; (например 0b0000000000001011 -> 0b1101000000000000).
; Число для инвертирования подается в регистре AX результат должен оставаться в этом же регистре.
;
; https://cs.itmo.ru/courses/51/modules/179/tasks/904

    xor     dx, dx
    mov     ecx, 16

.reverse:
    shr     ax, 1
    adc     dx, dx
    loop    .reverse

    mov     ax, dx
